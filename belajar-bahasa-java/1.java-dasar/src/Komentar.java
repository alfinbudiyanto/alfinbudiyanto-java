public class Komentar {
    public static void main(String[] args) {

        System.out.println(sum(10, 10));

    }

    /**
     * Method untuk menjumlahkan nilai1 dan nilai1
     * @param nilai1 angka pertama
     * @param nilai2 angka kedua
     * @return hasil menjumlahkan nilai1 dan nilai2
     */

    static int sum(int nilai1, int nilai2) {
        // Jumlahkan nilai1 ditambah nilai2
        return nilai1 + nilai2;
    }
}
